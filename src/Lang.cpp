	static std::string lowerStr(const std::string& s)
	{
		std::string r = s;
		for (size_t i = 0; i < r.size(); ++i)
			if (r[i] >= 'A' && r[i] <= 'Z')
				r[i] = (char)(r[i] - 'A' + 'a');
		return r;
	}

	// game language from <Kenshi>/settings.cfg, line "language=ru_RU" (api-notes section 9); "" if unreadable
	static std::string readGameLanguage()
	{
		std::string dir;
		char path[MAX_PATH] = { 0 };
		if (GetModuleFileNameA(NULL, path, MAX_PATH) > 0)
		{
			std::string p(path);
			size_t slash = p.find_last_of("\\/");
			if (slash != std::string::npos)
				dir = p.substr(0, slash + 1);
		}
		// RE_Kenshi starts <Kenshi>\\RE_Kenshi\\Kenshi_x64.exe, settings.cfg lies one level up: try both
		std::string file = dir + "settings.cfg";
		std::ifstream in(file.c_str());
		if (!in && dir.size() > 1)
		{
			std::string d2 = dir.substr(0, dir.size() - 1);
			size_t sl = d2.find_last_of("\\/");
			if (sl != std::string::npos)
			{
				std::string file2 = d2.substr(0, sl + 1) + "settings.cfg";
				LogInfo("lang: %s not found, trying %s", file.c_str(), file2.c_str());
				file = file2;
				in.clear();
				in.open(file.c_str());
			}
		}
		if (!in)
		{
			LogInfo("lang: cannot open %s", file.c_str());
			return std::string();
		}
		LogInfo("lang: reading %s", file.c_str());
		std::string line;
		while (std::getline(in, line))
		{
			size_t eq = line.find('=');
			if (eq == std::string::npos)
				continue;
			std::string key = lowerStr(line.substr(0, eq));
			if (key != "language")
				continue;
			std::string v = line.substr(eq + 1);
			size_t b = v.find_first_not_of(" \t\r\n");
			size_t e = v.find_last_not_of(" \t\r\n");
			std::string val = b == std::string::npos ? std::string() : v.substr(b, e - b + 1);
			LogInfo("lang: settings line '%s' -> language value '%s'", line.c_str(), val.c_str());
			return val;
		}
		return std::string();
	}

	void LangInit()
	{
		const std::string& mode = GetConfig().uiLanguage;
		std::string game = readGameLanguage();
		bool gameRu = lowerStr(game) == "ru_ru";
		if (mode == "ru")
			g_ru = true;
		else if (mode == "en")
			g_ru = false;
		else
			g_ru = gameRu;
		g_inited = true;
		LogInfo("lang: ui_language=%s, game language='%s' -> UI text is %s%s", mode.c_str(), game.c_str(),
			g_ru ? "Russian" : "English",
			(g_ru && !gameRu) ? " (WARNING: the game font has no Cyrillic for this game language, expect empty squares)" : "");
	}

	bool LangIsRussian()
	{
		return g_ru;
	}

	const char* Tr(StrId id)
	{
		if ((int)id < 0 || (int)id >= (int)S_COUNT)
			return "";
		const StrRow& r = kStrings[id];
		return g_ru ? r.ru : r.en;
	}
